"""Generates the fuzzer dictionary for ObdsToFhirBundleMapperFuzzTest from the oBDS XSD.

The XSD ships in the io.github.bzkf:obds2-to-obds3 jar under schema/. Usage:

    unzip -p obds2-to-obds3-*.jar schema/oBDS_v3.0.4.xsd > oBDS.xsd
    python3 generate_fuzz_dictionary.py oBDS.xsd > \
      ../src/test/resources/io/github/bzkf/obdstofhir/mapper/mii/obds.dict
"""

import sys
import xml.etree.ElementTree as ET  # nosec B405 the XSD is a trusted, local file

XS = "{http://www.w3.org/2001/XMLSchema}"

# xs:date with and without time zones, which Jackson reads differently
DATE_TOKENS = [
    "+02:00",
    "+01:00",
    "-05:00",
    "+14:00",
    "-12:00",
    "Z",
    "2019-05-02",
    "2019-12-31+01:00",
    "1950-01-01",
]


def quote(token: str) -> str:
    escaped = token.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main(xsd_path: str) -> None:
    root = ET.parse(xsd_path).getroot()  # nosec B314 the XSD is a trusted, local file

    elements = sorted({e.attrib["name"] for e in root.iter(XS + "element") if "name" in e.attrib})
    attributes = sorted(
        {a.attrib["name"] for a in root.iter(XS + "attribute") if "name" in a.attrib}
    )
    enumerations = sorted({v.attrib["value"] for v in root.iter(XS + "enumeration")} - {""})

    lines = [
        f"# Generated by mappings/scripts/{__file__.rsplit('/', 1)[-1]} from the oBDS XSD.",
    ]
    lines += [quote(f"<{name}>") for name in elements]
    lines += [quote(f"</{name}>") for name in elements]
    lines += [quote(f' {name}="') for name in attributes]
    lines += [quote(value) for value in enumerations]
    lines += [quote(token) for token in DATE_TOKENS]
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
